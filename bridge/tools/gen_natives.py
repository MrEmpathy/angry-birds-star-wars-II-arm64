#!/usr/bin/env python3
"""Generate native-method trampoline table entries from a `natives.txt` list.

Input lines (from dexdump): `[static ]pkg.Class.method(SIG)RET`. Only classes matching --prefix are kept.
"""
import argparse
import re

JNI_TYPES = {"Z": "jboolean", "B": "jbyte", "C": "jchar", "S": "jshort", "I": "jint",
             "J": "jlong", "F": "jfloat", "D": "jdouble", "V": "void"}


def split_sig(sig):
    """Return (param type chars, return char) with references collapsed to 'L'."""
    params, i = [], 1
    while sig[i] != ")":
        j = i
        while sig[j] == "[":
            j += 1
        if sig[j] == "L":
            j = sig.index(";", j)
        params.append("L" if sig[i] in "L[" else sig[i])
        i = j + 1
    ret = sig[i + 1]
    return params, "L" if ret in "L[" else ret


def mangle(s):
    out = []
    for ch in s:
        if ch == "/":
            out.append("_")
        elif ch == "_":
            out.append("_1")
        elif ch == ";":
            out.append("_2")
        elif ch == "[":
            out.append("_3")
        elif ch.isascii() and ch.isalnum():
            out.append(ch)
        else:
            out.append("_0%04x" % ord(ch))
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("natives")
    ap.add_argument("out")
    ap.add_argument("--prefix", default="com.rovio.")
    args = ap.parse_args()
    rows = []
    for line in open(args.natives, encoding="utf-8"):
        m = re.match(r"(static )?([\w.$]+)\.([\w$]+)(\(.*)$", line.strip())
        if not m or not m.group(2).startswith(args.prefix):
            continue
        cls = m.group(2).replace(".", "/")
        name, sig = m.group(3), m.group(4)
        params, ret = split_sig(sig)
        ctypes = [JNI_TYPES.get(p, "jobject") for p in params]
        rtype = JNI_TYPES.get(ret, "jobject")
        slot = len(rows)
        targs = ", ".join([str(slot), rtype] + ctypes)
        rows.append(f'{{"{cls}", "{name}", "{sig}", "Java_{mangle(cls)}_{mangle(name)}", '
                    f"reinterpret_cast<void*>(&native_tramp<{targs}>)}},")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_natives.py; do not edit.\n")
        f.write("\n".join(rows) + "\n")
    print(f"{len(rows)} native trampolines -> {args.out}")


if __name__ == "__main__":
    main()
